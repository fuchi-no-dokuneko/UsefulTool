// Build only Timeline Video Studio. Do not regenerate another tool's files.
import { promises as fs } from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = await fs.readFile(path.join(root, "video-editor.html"), "utf8");
const output = path.join(root, "build", "video-studio");
const references = new Set();
let offline = source;
for (const match of source.matchAll(
  /<link\s+rel="stylesheet"\s+href="([^"]+)"\s*\/?\s*>/g,
)) {
  const ref = match[1].replace(/[?#].*$/, "");
  if (!ref.startsWith("assets/pages/video-studio/"))
    throw new Error("Unexpected studio stylesheet: " + ref);
  references.add(ref);
  const css = (await fs.readFile(path.join(root, ref), "utf8")).replace(
    /<\/style/gi,
    "<\\/style",
  );
  offline = offline.replace(
    match[0],
    () => `<style data-inlined-from="${ref}">\n${css}\n</style>`,
  );
}
for (const match of source.matchAll(/<script\s+src="([^"]+)"\s*><\/script>/g)) {
  const ref = match[1].replace(/[?#].*$/, "");
  if (
    !ref.startsWith("assets/pages/video-studio/") &&
    ref !== "assets/pages/video-editor.js"
  )
    throw new Error("Unexpected studio script: " + ref);
  references.add(ref);
  const js = (await fs.readFile(path.join(root, ref), "utf8")).replace(
    /<\/script/gi,
    "<\\/script",
  );
  offline = offline.replace(
    match[0],
    () => `<script data-inlined-from="${ref}">\n${js}\n</script>`,
  );
}
offline = offline
  .replace(
    "<!doctype html>",
    "<!doctype html>\n<!-- Generated by scripts/build-video-studio.mjs. Do not edit directly. -->",
  )
  .replace("script-src 'self'", "script-src 'self' 'unsafe-inline'")
  .replace('href="offline/video-editor.html"', 'href="video-editor.html"');
if (/<script[^>]+src=|<link[^>]+rel="stylesheet"/.test(offline))
  throw new Error("Offline studio still has a runtime dependency.");
if (Buffer.byteLength(offline) > 2 * 1024 * 1024)
  throw new Error("Offline studio exceeds its 2 MiB size budget.");
await fs.mkdir(path.join(root, "offline"), { recursive: true });
await fs.writeFile(path.join(root, "offline/video-editor.html"), offline);
const manifestPath = path.join(root, "offline/manifest.json");
const manifest = JSON.parse(await fs.readFile(manifestPath, "utf8"));
const entry = {
  file: "video-editor.html",
  bytes: Buffer.byteLength(offline),
  sha256: crypto.createHash("sha256").update(offline).digest("hex"),
};
const index = manifest.pages.findIndex((page) => page.file === entry.file);
if (index >= 0) manifest.pages[index] = entry;
else {
  manifest.pages.push(entry);
  manifest.pages.sort((a, b) => a.file.localeCompare(b.file));
}
await fs.writeFile(manifestPath, JSON.stringify(manifest, null, 2) + "\n");

// A separate deployable directory prevents publishing unrelated workspace files.
await fs.mkdir(path.join(output, "offline"), { recursive: true });
await fs.writeFile(path.join(output, "video-editor.html"), source);
await fs.writeFile(path.join(output, "index.html"), source);
await fs.writeFile(path.join(output, "offline/video-editor.html"), offline);
for (const ref of references) {
  await fs.mkdir(path.dirname(path.join(output, ref)), { recursive: true });
  await fs.copyFile(path.join(root, ref), path.join(output, ref));
}
await fs.writeFile(
  path.join(output, "_headers"),
  `/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Content-Security-Policy: frame-ancestors 'none'
/assets/*
  Cache-Control: public, max-age=0, must-revalidate
/offline/*
  Content-Disposition: attachment
`,
);
console.log(
  `Built offline/video-editor.html (${entry.bytes} bytes) and build/video-studio/.`,
);
